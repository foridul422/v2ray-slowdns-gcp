#!/bin/bash
# ============================================================
#  Phase 1 — Environment Setup
#  V2Ray + SlowDNS on Google Cloud Shell
# ============================================================

# ── Colors ──────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m' # No Color

# ── Logging ─────────────────────────────────────────────────
LOG_FILE="$HOME/v2ray-slowdns-gcp/output/install.log"
mkdir -p "$HOME/v2ray-slowdns-gcp/output/keys"
mkdir -p "$HOME/v2ray-slowdns-gcp/config"

log()  { echo -e "${GREEN}[✔]${NC} $1" | tee -a "$LOG_FILE"; }
warn() { echo -e "${YELLOW}[⚠]${NC} $1" | tee -a "$LOG_FILE"; }
err()  { echo -e "${RED}[✘]${NC} $1" | tee -a "$LOG_FILE"; }
info() { echo -e "${CYAN}[i]${NC} $1" | tee -a "$LOG_FILE"; }
banner() {
    echo -e "\n${BOLD}${CYAN}═══════════════════════════════════════${NC}"
    echo -e "${BOLD}${CYAN}  $1${NC}"
    echo -e "${BOLD}${CYAN}═══════════════════════════════════════${NC}\n"
}

# ── Banner ──────────────────────────────────────────────────
clear
echo -e "${BOLD}${CYAN}"
cat << 'EOF'
 __   ____  ____  __   _  _     ___  __    __   _  _  ____  __ _  _  _ 
 \ \ / /  \/  _ \/ /  | \/ |   / __||  |  /  \ | || ||  _ \|  \ || \/ |
  \ V /   /   __/ /   |    |   \__ \|  |_| () || \/ ||  _ <|     ||    |
   \_/ |_|  \___|_|   |_/\_|   |___/|____|\__/  \__/ |____/|_|\__|_|/\_|

         V2Ray + SlowDNS | Google Cloud Shell Setup
EOF
echo -e "${NC}"

banner "Phase 1: Environment Setup"

# ── 1. Detect Architecture ──────────────────────────────────
info "Detecting system architecture..."
ARCH=$(uname -m)
case "$ARCH" in
    x86_64)   ARCH_NAME="amd64"  ;;
    aarch64)  ARCH_NAME="arm64"  ;;
    armv7l)   ARCH_NAME="arm32"  ;;
    *)
        err "Unsupported architecture: $ARCH"
        exit 1
        ;;
esac
log "Architecture: $ARCH ($ARCH_NAME)"

# ── 2. Detect OS ────────────────────────────────────────────
OS=$(uname -s | tr '[:upper:]' '[:lower:]')
log "OS: $OS"

# ── 3. Check if running in GCP Cloud Shell ──────────────────
if [[ -n "$CLOUD_SHELL" ]] || [[ -f /etc/google_cloud_shell ]]; then
    log "Running inside Google Cloud Shell ✓"
    IS_CLOUDSHELL=true
else
    warn "Not detected as Google Cloud Shell. Continuing anyway..."
    IS_CLOUDSHELL=false
fi

# ── 4. Install required tools ───────────────────────────────
banner "Installing required tools"

TOOLS=(curl wget unzip openssl jq screen socat dnsutils)
MISSING=()

for tool in "${TOOLS[@]}"; do
    if ! command -v "$tool" &>/dev/null; then
        MISSING+=("$tool")
    else
        log "$tool — already installed"
    fi
done

if [[ ${#MISSING[@]} -gt 0 ]]; then
    info "Installing missing tools: ${MISSING[*]}"
    sudo apt-get update -qq 2>>"$LOG_FILE"
    sudo apt-get install -y "${MISSING[@]}" -qq 2>>"$LOG_FILE"
    for tool in "${MISSING[@]}"; do
        if command -v "$tool" &>/dev/null; then
            log "$tool — installed successfully"
        else
            warn "$tool — could not install (non-critical, continuing...)"
        fi
    done
fi

# ── 5. Get Public IP ────────────────────────────────────────
banner "Detecting Public IP"

PUBLIC_IP=""
IP_SOURCES=(
    "https://ifconfig.me"
    "https://api.ipify.org"
    "https://icanhazip.com"
    "https://ident.me"
)

for source in "${IP_SOURCES[@]}"; do
    IP=$(curl -s --max-time 5 "$source" 2>/dev/null | tr -d '[:space:]')
    if [[ "$IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
        PUBLIC_IP="$IP"
        log "Public IP detected: ${BOLD}$PUBLIC_IP${NC} (via $source)"
        break
    fi
done

if [[ -z "$PUBLIC_IP" ]]; then
    err "Could not detect public IP automatically."
    echo -ne "${YELLOW}Enter your public IP manually: ${NC}"
    read -r PUBLIC_IP
fi

# ── 6. Save environment config ──────────────────────────────
ENV_FILE="$HOME/v2ray-slowdns-gcp/config/env.conf"
cat > "$ENV_FILE" << EOF
# Auto-generated by Phase 1 Setup
PUBLIC_IP="$PUBLIC_IP"
ARCH_NAME="$ARCH_NAME"
OS="$OS"
IS_CLOUDSHELL="$IS_CLOUDSHELL"
LOG_FILE="$LOG_FILE"
INSTALL_DIR="$HOME/v2ray-slowdns-gcp"
CONFIG_DIR="$HOME/v2ray-slowdns-gcp/config"
OUTPUT_DIR="$HOME/v2ray-slowdns-gcp/output"
KEYS_DIR="$HOME/v2ray-slowdns-gcp/output/keys"
EOF
log "Environment config saved → $ENV_FILE"

# ── 7. NS Record Instruction ────────────────────────────────
echo ""
echo -e "${BOLD}${GREEN}╔══════════════════════════════════════════════════════╗${NC}"
echo -e "${BOLD}${GREEN}║         🌐  DNS NS RECORD SETUP REQUIRED             ║${NC}"
echo -e "${BOLD}${GREEN}╠══════════════════════════════════════════════════════╣${NC}"
echo -e "${BOLD}${GREEN}║                                                      ║${NC}"
echo -e "${BOLD}${GREEN}║  Your Server Public IP:  ${CYAN}${PUBLIC_IP}${GREEN}             ║${NC}"
echo -e "${BOLD}${GREEN}║                                                      ║${NC}"
echo -e "${BOLD}${GREEN}║  Domain এ এই records set করো:                       ║${NC}"
echo -e "${BOLD}${GREEN}║                                                      ║${NC}"
echo -e "${BOLD}${GREEN}║  Type: A      Host: ns1    Value: ${CYAN}${PUBLIC_IP}${GREEN}   ║${NC}"
echo -e "${BOLD}${GREEN}║  Type: NS     Host: tunnel  Value: ns1.YOURDOMAIN    ║${NC}"
echo -e "${BOLD}${GREEN}║                                                      ║${NC}"
echo -e "${BOLD}${GREEN}║  Example (yourdomain.com):                           ║${NC}"
echo -e "${BOLD}${GREEN}║    ns1.yourdomain.com  → A     → ${CYAN}${PUBLIC_IP}${GREEN}   ║${NC}"
echo -e "${BOLD}${GREEN}║    tunnel.yourdomain.com → NS  → ns1.yourdomain.com ║${NC}"
echo -e "${BOLD}${GREEN}║                                                      ║${NC}"
echo -e "${BOLD}${GREEN}╚══════════════════════════════════════════════════════╝${NC}"
echo ""

# ── 8. Ask user for domain ──────────────────────────────────
echo -ne "${CYAN}তোমার domain টা enter করো${NC} (example: yourdomain.com): "
read -r USER_DOMAIN
USER_DOMAIN=$(echo "$USER_DOMAIN" | tr '[:upper:]' '[:lower:]' | sed 's/^www\.//')

echo -ne "${CYAN}SlowDNS tunnel subdomain${NC} (default: tunnel): "
read -r TUNNEL_SUB
TUNNEL_SUB=${TUNNEL_SUB:-tunnel}

echo -ne "${CYAN}NS subdomain${NC} (default: ns1): "
read -r NS_SUB
NS_SUB=${NS_SUB:-ns1}

TUNNEL_DOMAIN="${TUNNEL_SUB}.${USER_DOMAIN}"
NS_DOMAIN="${NS_SUB}.${USER_DOMAIN}"

# Save to env
cat >> "$ENV_FILE" << EOF
USER_DOMAIN="$USER_DOMAIN"
TUNNEL_DOMAIN="$TUNNEL_DOMAIN"
NS_DOMAIN="$NS_DOMAIN"
NS_SUB="$NS_SUB"
TUNNEL_SUB="$TUNNEL_SUB"
EOF

log "Domain config saved: $TUNNEL_DOMAIN → NS → $NS_DOMAIN → $PUBLIC_IP"

# ── 9. Summary ──────────────────────────────────────────────
echo ""
banner "Phase 1 — Complete ✓"
echo -e "  Public IP   : ${BOLD}$PUBLIC_IP${NC}"
echo -e "  Domain      : ${BOLD}$USER_DOMAIN${NC}"
echo -e "  NS Record   : ${BOLD}$NS_DOMAIN → $PUBLIC_IP${NC}"
echo -e "  Tunnel NS   : ${BOLD}$TUNNEL_DOMAIN → NS → $NS_DOMAIN${NC}"
echo ""
echo -e "${YELLOW}👉 Domain এ NS record set করে নাও, তারপর Phase 2 (SlowDNS) চালাও!${NC}"
echo ""
